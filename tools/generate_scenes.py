#!/usr/bin/env python3
"""Generate the parity scene tables from tools/scenes.json (single source of
truth) into:

  - tools/bullet_scenes.h            (C++ recorder, bullet_record.cpp)
  - crates/bullet/examples/scenes_generated.rs  (Rust recorder, record_scenes.rs)

Both generated files are DO NOT EDIT. tools/parity.py reruns this generator
before every recording, so the generated code always matches the JSON.

Usage:
    python tools/generate_scenes.py
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCENES_JSON = os.path.join(ROOT, "tools", "scenes.json")
C_HEADER = os.path.join(ROOT, "tools", "bullet_scenes.h")
# Lives under src/ (not examples/) so cargo does not treat it as a standalone
# example; record_scenes.rs pulls it in with #[path].
RS_TABLE = os.path.join(ROOT, "crates", "bullet", "src", "parity_scenes.rs")

SHAPE_TYPES = {"box", "sphere", "capsule", "cylinder", "cone", "plane", "mesh"}
SHAPE_ENUM = {"box": "SHAPE_BOX", "sphere": "SHAPE_SPHERE", "capsule": "SHAPE_CAPSULE",
              "cylinder": "SHAPE_CYLINDER", "cone": "SHAPE_CONE", "plane": "SHAPE_PLANE",
              "mesh": "SHAPE_MESH"}


def shape_params(shape):
    """Flatten a shape dict into (type, [params...]) with the union layout:
    box: 3 half extents; sphere: radius; capsule/cylinder/cone: radius,
    half_height; plane: normal xyz + constant. Padded to 6 floats. Mesh bodies
    carry their geometry in a dedicated MeshSpec; the params array stays
    all-zero so the union layout still parses."""
    t = shape["type"]
    if t == "box":
        return t, list(shape["half_extents"])
    if t == "sphere":
        return t, [shape["radius"]]
    if t in ("capsule", "cylinder", "cone"):
        return t, [shape["radius"], shape["half_height"]]
    if t == "plane":
        return t, list(shape["normal"]) + [shape["constant"]]
    if t == "mesh":
        return t, [0.0] * 6
    raise ValueError(f"unknown shape type {t!r}")


def mesh_vertices(shape):
    """Expand a height-grid mesh spec into (nx, nz, vertices) where vertices is
    a flat [x, y, z] list in z-major order (index z*nx + x) - the same vertex
    order as the falling_mesh demo, so the two engines build identical
    geometry."""
    nx, nz = shape["grid"]
    ox, oz = shape["origin"]
    dx, dz = shape["cell"]
    heights = shape["heights"]
    if len(heights) != nx * nz:
        raise ValueError(f"mesh heights: expected {nx * nz} values, got {len(heights)}")
    verts = []
    for z in range(nz):
        for x in range(nx):
            h = heights[z * nx + x]
            verts.extend([ox + x * dx, h, oz + z * dz])
    return nx, nz, verts


def mesh_indices(nx, nz):
    """Triangle indices for the height grid with the falling_mesh demo winding
    ([v00, v11, v10] / [v00, v01, v11], +Y face normals on a flat grid)."""
    idx = []
    for z in range(nz - 1):
        for x in range(nx - 1):
            v00 = z * nx + x
            v10 = v00 + 1
            v01 = v00 + nx
            v11 = v01 + 1
            idx.extend([v00, v11, v10, v00, v01, v11])
    return idx


def fmt(v, precision=9):
    """Format a float; ensure the literal has a decimal point so Rust and C++
    both parse it as a floating-point constant (%.9g drops it for integers)."""
    s = f"{v:.{precision}g}"
    if "." not in s and "e" not in s and "E" not in s:
        s += ".0"
    return s


def gen_c(scenes):
    lines = [
        "// Auto-generated by tools/generate_scenes.py from tools/scenes.json - DO NOT EDIT.",
        "#pragma once",
        "",
        "#include \"btBulletDynamicsCommon.h\"",
        "",
        "enum ShapeType { SHAPE_BOX, SHAPE_SPHERE, SHAPE_CAPSULE, SHAPE_CYLINDER, SHAPE_CONE, SHAPE_PLANE, SHAPE_MESH };",
        "",
        "struct MeshSpec {",
        "  int num_vertices;",
        "  const btScalar* vertices;  // num_vertices * 3 (x y z)",
        "  int num_triangles;",
        "  const int* indices;        // num_triangles * 3",
        "};",
        "",
        "struct BodySpec {",
        "  const char* name;",
        "  ShapeType shape;",
        "  btScalar params[6];",
        "  btScalar pos[3];",
        "  btScalar mass, friction, restitution;",
        "  int is_static;",
        "  btScalar velocity[3];",
        "  int ccd_on;",
        "  btScalar ccd_motion_threshold, ccd_swept_sphere_radius;",
        "  btScalar body_gravity[3];  // per-body gravity (implies disable_world_gravity)",
        "  int disable_world_gravity;  // BT_DISABLE_WORLD_GRAVITY: detach from world gravity",
        "  int no_contact_response;  // CF_NO_CONTACT_RESPONSE: trigger/sensor",
        "  int group, mask;  // collision filter; addRigidBody(body, group, mask)",
        "  const MeshSpec* mesh;  // non-null only for SHAPE_MESH",
        "};",
        "",
        "struct RaySpec {",
        "  btScalar from[3], to[3];",
        "  int all_hits;  // 1 = all-hits probe, 0 = closest",
        "  int group, mask;  // ray filter (RayResultCallback::needsCollision order)",
        "};",
        "",
        "struct SceneSpec {",
        "  const char* name;",
        "  int num_bodies;",
        "  const BodySpec* bodies;",
        "  int num_record;",
        "  const char* const* record;",
        "  int dt_num, dt_den;",
        "  int frames;",
        "  int iterations;",
        "  btScalar gravity[3];",
        "  const char* const* pair_filter;  // {nameA, nameB} excluded pair, or null",
        "  int num_rays;",
        "  const RaySpec* rays;",
        "};",
        "",
    ]
    for name, sc in scenes.items():
        # Emit mesh geometry first so the body specs can reference it.
        for b in sc["bodies"]:
            if b["shape"]["type"] != "mesh":
                continue
            nx, nz, verts = mesh_vertices(b["shape"])
            idx = mesh_indices(nx, nz)
            vs = ", ".join(f"btScalar({fmt(x)})" for x in verts)
            is_ = ", ".join(str(i) for i in idx)
            lines.append(f"static const btScalar k{name}_{b['name']}_verts[] = {{ {vs} }};")
            lines.append(f"static const int k{name}_{b['name']}_idx[] = {{ {is_} }};")
            lines.append(f"static const MeshSpec k{name}_{b['name']}_mesh = "
                         f"{{ {len(verts) // 3}, k{name}_{b['name']}_verts, "
                         f"{len(idx) // 3}, k{name}_{b['name']}_idx }};")
        lines.append(f"static const BodySpec k{name}_bodies[] = {{")
        for b in sc["bodies"]:
            t, params = shape_params(b["shape"])
            params = (params + [0.0] * 6)[:6]
            p = ", ".join(f"btScalar({fmt(x)})" for x in params)
            pos = ", ".join(f"btScalar({fmt(x)})" for x in b["position"])
            mass = fmt(b.get("mass", 0.0))
            if b.get("mass", 0.0) == 0:
                fr, re = "0.5", "0.0"
            else:
                fr = fmt(b.get("friction", 0.5))
                re = fmt(b.get("restitution", 0.0))
            st = 1 if b.get("mass", 0.0) == 0 else 0
            vel = b.get("velocity", [0.0, 0.0, 0.0])
            vel_s = ", ".join(f"btScalar({fmt(x)})" for x in vel)
            ccd = b.get("ccd")
            ccd_on = 1 if ccd else 0
            ccd_mt = ccd.get("motion_threshold", 0.0) if ccd else 0.0
            ccd_sr = ccd.get("swept_sphere_radius", 0.0) if ccd else 0.0
            mesh_ref = f"&k{name}_{b['name']}_mesh" if t == "mesh" else "nullptr"
            bg = b.get("gravity")
            dwg = 1 if bg else 0
            bg_s = ", ".join(f"btScalar({fmt(x)})" for x in (bg if bg else [0.0, 0.0, 0.0]))
            ncr = 1 if b.get("no_contact_response") else 0
            grp = b.get("group", 1)
            msk = b.get("mask", -1)
            lines.append(f"  {{\"{b['name']}\", {SHAPE_ENUM[t]}, {{{p}}}, {{{pos}}}, "
                         f"btScalar({mass}), btScalar({fr}), btScalar({re}), {st}, "
                         f"{{{vel_s}}}, {ccd_on}, btScalar({fmt(ccd_mt)}), "
                         f"btScalar({fmt(ccd_sr)}), {{{bg_s}}}, {dwg}, {ncr}, {grp}, {msk}, "
                         f"{mesh_ref}}},")
        lines.append("};")
        lines.append("")
        rec = ", ".join(f"\"{r}\"" for r in sc["record"])
        dt_num, dt_den = sc["dt"]
        g = ", ".join(fmt(x) for x in sc["gravity"])
        lines.append(f"static const char* const k{name}_record[] = {{{rec}}};")
        pf = sc.get("pair_filter")
        if pf:
            lines.append(f"static const char* const k{name}_pair_filter[] = "
                         f"{{ \"{pf[0]}\", \"{pf[1]}\" }};")
        pf_ref = f"k{name}_pair_filter" if pf else "nullptr"
        rays = sc.get("rays", [])
        if rays:
            lines.append(f"static const RaySpec k{name}_rays[] = {{")
            for r in rays:
                if r["mode"] not in ("all", "closest"):
                    raise ValueError(f"bad ray mode {r['mode']!r}")
                fr = ", ".join(f"btScalar({fmt(x)})" for x in r["from"])
                to = ", ".join(f"btScalar({fmt(x)})" for x in r["to"])
                mode = 1 if r["mode"] == "all" else 0
                rgrp = r.get("group", 1)
                rmsk = r.get("mask", -1)
                lines.append(f"  {{{{{fr}}}, {{{to}}}, {mode}, {rgrp}, {rmsk}}},")
            lines.append("};")
        rays_ref = f"k{name}_rays" if rays else "nullptr"
        lines.append(f"static const SceneSpec k{name} = {{\"{name}\", {len(sc['bodies'])}, k{name}_bodies, "
                     f"{len(sc['record'])}, k{name}_record, {dt_num}, {dt_den}, "
                     f"{sc['frames']}, {sc['iterations']}, {{{g}}}, "
                     f"{pf_ref}, {len(rays)}, {rays_ref}}};")
        lines.append("")
    lines.append("static const SceneSpec* kScenes[] = {")
    for name in scenes:
        lines.append(f"  &k{name},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def gen_rs(scenes):
    lines = [
        "// Auto-generated by tools/generate_scenes.py from tools/scenes.json - DO NOT EDIT.",
        "// Included by record_scenes.rs via #[path]; not part of the library.",
        "",
        "#![allow(dead_code)]",
        "",
        "#[derive(Clone, Copy)]",
        "pub enum ShapeSpec {",
        "    Box([f32; 3]),",
        "    Sphere(f32),",
        "    Capsule(f32, f32),",
        "    Cylinder(f32, f32),",
        "    Cone(f32, f32),",
        "    Plane([f32; 4]),",
        "    Mesh(&'static [f32], &'static [u32]),",
        "}",
        "",
        "pub struct BodySpec {",
        "    pub name: &'static str,",
        "    pub shape: ShapeSpec,",
        "    pub position: [f32; 3],",
        "    pub mass: f32,",
        "    pub friction: f32,",
        "    pub restitution: f32,",
        "    pub is_static: bool,",
        "    pub velocity: [f32; 3],",
        "    pub ccd_on: bool,",
        "    pub ccd_motion_threshold: f32,",
        "    pub ccd_swept_sphere_radius: f32,",
        "    pub body_gravity: [f32; 3],",
        "    pub disable_world_gravity: bool,",
        "    pub no_contact_response: bool,",
        "    pub group: u16,",
        "    pub mask: u16,",
        "}",
        "",
        "pub struct RaySpec {",
        "    pub from: [f32; 3],",
        "    pub to: [f32; 3],",
        "    pub all_hits: bool,",
        "    pub group: u16,",
        "    pub mask: u16,",
        "}",
        "",
        "pub struct SceneSpec {",
        "    pub bodies: &'static [BodySpec],",
        "    pub record: &'static [&'static str],",
        "    pub dt_num: u32,",
        "    pub dt_den: u32,",
        "    pub frames: u32,",
        "    pub iterations: u32,",
        "    pub gravity: [f32; 3],",
        "    pub pair_filter: Option<(&'static str, &'static str)>,",
        "    pub rays: &'static [RaySpec],",
        "}",
        "",
        "pub const SCENES: &[(&str, SceneSpec)] = &[",
    ]
    for name, sc in scenes.items():
        lines.append(f"    (\"{name}\", SceneSpec {{")
        lines.append("        bodies: &[")
        for b in sc["bodies"]:
            t, params = shape_params(b["shape"])
            if t == "box":
                shape = f"ShapeSpec::Box([{', '.join(fmt(x) for x in params)}])"
            elif t == "sphere":
                shape = f"ShapeSpec::Sphere({fmt(params[0])})"
            elif t in ("capsule", "cylinder", "cone"):
                cap = t[0].upper() + t[1:]
                shape = f"ShapeSpec::{cap}({fmt(params[0])}, {fmt(params[1])})"
            elif t == "plane":
                shape = f"ShapeSpec::Plane([{', '.join(fmt(x) for x in params)}])"
            else:  # mesh
                _, _, verts = mesh_vertices(b["shape"])
                nx, nz = b["shape"]["grid"]
                idx = mesh_indices(nx, nz)
                vs = ", ".join(fmt(x) for x in verts)
                is_ = ", ".join(str(i) for i in idx)
                shape = f"ShapeSpec::Mesh(&[{vs}], &[{is_}])"
            pos = f"[{', '.join(fmt(x) for x in b['position'])}]"
            mass = fmt(b.get("mass", 0.0))
            if b.get("mass", 0.0) == 0:
                fr, re, st = "0.5", "0.0", "true"
            else:
                fr, re = fmt(b.get("friction", 0.5)), fmt(b.get("restitution", 0.0))
                st = "false"
            vel = b.get("velocity", [0.0, 0.0, 0.0])
            vel_s = ", ".join(fmt(x) for x in vel)
            ccd = b.get("ccd")
            ccd_on = "true" if ccd else "false"
            ccd_mt = ccd.get("motion_threshold", 0.0) if ccd else 0.0
            ccd_sr = ccd.get("swept_sphere_radius", 0.0) if ccd else 0.0
            bg = b.get("gravity")
            dwg = "true" if bg else "false"
            bg_s = ", ".join(fmt(x) for x in (bg if bg else [0.0, 0.0, 0.0]))
            ncr = "true" if b.get("no_contact_response") else "false"
            grp = b.get("group", 1) & 0xFFFF
            msk = b.get("mask", -1) & 0xFFFF
            lines.append(f"            BodySpec {{ name: \"{b['name']}\", shape: {shape}, "
                         f"position: {pos}, mass: {mass}, friction: {fr}, restitution: {re}, "
                         f"is_static: {st}, velocity: [{vel_s}], ccd_on: {ccd_on}, "
                         f"ccd_motion_threshold: {fmt(ccd_mt)}, "
                         f"ccd_swept_sphere_radius: {fmt(ccd_sr)}, "
                         f"body_gravity: [{bg_s}], disable_world_gravity: {dwg}, "
                         f"no_contact_response: {ncr}, group: {grp}u16, mask: {msk}u16 }},")
        lines.append("        ],")
        rec = ", ".join(f"\"{r}\"" for r in sc["record"])
        dt_num, dt_den = sc["dt"]
        g = ", ".join(fmt(x) for x in sc["gravity"])
        lines.append(f"        record: &[{rec}],")
        lines.append(f"        dt_num: {dt_num}, dt_den: {dt_den},")
        lines.append(f"        frames: {sc['frames']}, iterations: {sc['iterations']},")
        lines.append(f"        gravity: [{g}],")
        pf = sc.get("pair_filter")
        pf_rs = f"Some((\"{pf[0]}\", \"{pf[1]}\"))" if pf else "None"
        lines.append(f"        pair_filter: {pf_rs},")
        rays = sc.get("rays", [])
        if rays:
            lines.append("        rays: &[")
            for r in rays:
                if r["mode"] not in ("all", "closest"):
                    raise ValueError(f"bad ray mode {r['mode']!r}")
                fr = ", ".join(fmt(x) for x in r["from"])
                to = ", ".join(fmt(x) for x in r["to"])
                mode = "true" if r["mode"] == "all" else "false"
                rgrp = r.get("group", 1) & 0xFFFF
                rmsk = r.get("mask", -1) & 0xFFFF
                lines.append(f"            RaySpec {{ from: [{fr}], to: [{to}], "
                             f"all_hits: {mode}, group: {rgrp}u16, mask: {rmsk}u16 }},")
            lines.append("        ],")
        else:
            lines.append("        rays: &[],")
        lines.append("    }),")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main():
    with open(SCENES_JSON, "r", encoding="utf-8") as f:
        data = json.load(f)
    scenes = data["scenes"]
    for name, sc in scenes.items():
        for b in sc["bodies"]:
            if b["shape"]["type"] not in SHAPE_TYPES:
                print(f"error: {name}/{b['name']}: bad shape type", file=sys.stderr)
                return 1
            if b.get("mass", 0.0) == 0 and "friction" in b and b["friction"] != 0.5:
                print(f"warning: {name}/{b['name']}: static body friction {b['friction']} "
                      f"differs from default 0.5; static friction is not set via shape spec", file=sys.stderr)
            if b["shape"]["type"] == "mesh":
                try:
                    mesh_vertices(b["shape"])
                except ValueError as e:
                    print(f"error: {name}/{b['name']}: {e}", file=sys.stderr)
                    return 1
    with open(C_HEADER, "w", encoding="utf-8", newline="\n") as f:
        f.write(gen_c(scenes))
    with open(RS_TABLE, "w", encoding="utf-8", newline="\n") as f:
        f.write(gen_rs(scenes))
    print(f"generated {C_HEADER}")
    print(f"generated {RS_TABLE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
