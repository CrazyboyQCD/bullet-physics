#!/usr/bin/env python3
"""Per-frame numerical comparison between the Bullet C++ and Rust recordings.

Reads the two CSV files produced by tools/bullet_record.cpp and
crates/bullet-physics/examples/record_scenes.rs (one line per frame:
`t px py pz qx qy qz qw`, %.6f) and reports per-frame position distance and
quaternion angle (double-cover aware), against the tolerances from
docs/parity-harness.md (position 1e-2, orientation angle 1e-2).

Exceedances are logged, not auto-failed: differences are collected first and
classified later in docs/bullet-compare.md (known trade-off vs implementation
problem vs unknown).

Usage:
    python tools/compare.py <bullet.csv> <rust.csv> [--scene NAME] [--tol-pos X] [--tol-ang X]
"""

import argparse
import datetime
import math
import sys


def parse_csv(path):
    """Return list of (t, px, py, pz, qx, qy, qz, qw) tuples parsed as floats."""
    rows = []
    with open(path, "r", encoding="utf-8") as f:
        for lineno, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) != 8:
                print(f"warning: {path}:{lineno}: expected 8 columns, got {len(parts)}", file=sys.stderr)
                continue
            try:
                rows.append(tuple(float(p) for p in parts))
            except ValueError:
                print(f"warning: {path}:{lineno}: unparsable line: {line!r}", file=sys.stderr)
    return rows


def quat_angle(q1, q2):
    """Angle (rad) between two quaternions (x y z w), taking the double cover
    into account: min(angle(q1,q2), angle(-q1,q2)) = 2*acos(|dot|)."""
    dot = (q1[0] * q2[0] + q1[1] * q2[1] + q1[2] * q2[2] + q1[3] * q2[3])
    return 2.0 * math.acos(min(1.0, abs(dot)))


def compare(bullet, rust, tol_pos, tol_ang):
    """Return a report dict and the list of exceedances (frame idx, t, pos, ang)."""
    n = min(len(bullet), len(rust))
    if len(bullet) != len(rust):
        print(f"warning: frame count differs: bullet={len(bullet)} rust={len(rust)}", file=sys.stderr)

    max_pos = (0.0, -1)
    max_ang = (0.0, -1)
    sum_pos = 0.0
    sum_ang = 0.0
    exceed = []

    for i in range(n):
        pb = bullet[i]
        pr = rust[i]
        pos = math.sqrt(sum((pr[k] - pb[k]) ** 2 for k in range(1, 4)))
        ang = quat_angle(pb[4:8], pr[4:8])
        if pos > max_pos[0]:
            max_pos = (pos, i)
        if ang > max_ang[0]:
            max_ang = (ang, i)
        sum_pos += pos
        sum_ang += ang
        if pos > tol_pos or ang > tol_ang:
            exceed.append((i, bullet[i][0], pos, ang))

    return {
        "frames": n,
        "max_pos": max_pos,
        "max_ang": max_ang,
        "mean_pos": sum_pos / n if n else 0.0,
        "mean_ang": sum_ang / n if n else 0.0,
        "exceed": exceed,
    }


def build_markdown(args, bullet, rust, r):
    """Return a markdown report section (numbers only, machine generated) that
    can be pasted into the scene section of docs/bullet-compare.md. Analysis
    text (classification) stays manual below it."""
    max_pos_frame = r["max_pos"][1]
    max_ang_frame = r["max_ang"][1]
    lines = [
        f"### Generated report (auto-generated by tools/parity.py, {datetime.date.today().isoformat()})",
        "",
        f"Scene: {args.scene} ({args.precision}), {r['frames']} frames "
        f"(bullet={len(bullet)}, rust={len(rust)})",
        "",
        "| Metric | Value | Frame (t) |",
        "|---|---|---|",
        f"| Position max dev | {r['max_pos'][0]:.6f} | {max_pos_frame} ({bullet[max_pos_frame][0]:.6f}) |",
        f"| Position mean dev | {r['mean_pos']:.6f} | - |",
        f"| Orientation angle max dev | {r['max_ang'][0]:.6f} rad | {max_ang_frame} ({bullet[max_ang_frame][0]:.6f}) |",
        f"| Orientation angle mean dev | {r['mean_ang']:.6f} rad | - |",
    ]
    if r["exceed"]:
        frames = [str(i) for i, _, _, _ in r["exceed"]]
        span = f"{frames[0]}-{frames[-1]}" if len(frames) > 1 else frames[0]
        lines.append(f"| Exceedances (pos tol {args.tol_pos}, ang tol {args.tol_ang}) | {len(r['exceed'])} | frames {span} |")
        lines += ["", "Exceedance frames:"]
        for i, t, pos, ang in r["exceed"][:20]:
            lines.append(f"- frame {i} (t={t:.6f}): pos={pos:.6f} ang={ang:.6f}")
        if len(r["exceed"]) > 20:
            lines.append(f"- ... and {len(r['exceed']) - 20} more")
    else:
        lines.append(f"| Exceedances (pos tol {args.tol_pos}, ang tol {args.tol_ang}) | 0 | - |")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("bullet_csv", help="recording from tools/bullet_record (Bullet C++)")
    ap.add_argument("rust_csv", help="recording from record_scenes example (this crate)")
    ap.add_argument("--scene", default="falling_box", help="scene name for the report header")
    ap.add_argument("--precision", default="f32", choices=["f32", "f64"], help="precision pair (default f32)")
    ap.add_argument("--tol-pos", type=float, default=1e-2, help="position tolerance (default 1e-2)")
    ap.add_argument("--tol-ang", type=float, default=1e-2, help="orientation angle tolerance, rad (default 1e-2)")
    ap.add_argument("--report-md", metavar="FILE", help="write a markdown report section to FILE (for docs/bullet-compare.md)")
    args = ap.parse_args()

    bullet = parse_csv(args.bullet_csv)
    rust = parse_csv(args.rust_csv)
    r = compare(bullet, rust, args.tol_pos, args.tol_ang)

    print(f"scene: {args.scene} ({args.precision})")
    print(f"frames: {r['frames']} (bullet={len(bullet)}, rust={len(rust)})")
    print(f"position   max={r['max_pos'][0]:.6f} @ frame {r['max_pos'][1]} "
          f"(t={bullet[r['max_pos'][1]][0]:.6f}), mean={r['mean_pos']:.6f}")
    print(f"orientation angle max={r['max_ang'][0]:.6f} rad @ frame {r['max_ang'][1]} "
          f"(t={bullet[r['max_ang'][1]][0]:.6f}), mean={r['mean_ang']:.6f}")
    print(f"tolerances: pos={args.tol_pos}, ang={args.tol_ang}")
    print(f"exceedances: {len(r['exceed'])}")
    for i, t, pos, ang in r["exceed"][:20]:
        flag = "POS" if pos > args.tol_pos else ""
        if pos > args.tol_pos and ang > args.tol_ang:
            flag = "POS+ANG"
        elif ang > args.tol_ang:
            flag = "ANG"
        print(f"  frame {i:4d} t={t:.6f} pos={pos:.6f} ang={ang:.6f} [{flag}]")
    if len(r["exceed"]) > 20:
        print(f"  ... and {len(r['exceed']) - 20} more")

    if args.report_md:
        with open(args.report_md, "w", encoding="utf-8") as f:
            f.write(build_markdown(args, bullet, rust, r))
        print(f"report section written to {args.report_md}")

    # Exit code: 0 = within tolerance, 1 = exceedances (for CI-friendly runs).
    sys.exit(1 if r["exceed"] else 0)


if __name__ == "__main__":
    main()
